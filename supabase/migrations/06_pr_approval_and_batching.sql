-- 0. CLEANUP PREVIOUS OBJECTS TO ENSURE DDL COMPILATION
DROP VIEW IF EXISTS public.v_sap_consolidated_batch_payload CASCADE;
DROP FUNCTION IF EXISTS public.approve_staged_requisitions(text[], text);
DROP TABLE IF EXISTS public.erp_staged_requisitions CASCADE;
DROP TABLE IF EXISTS public.erp_requisition_batches CASCADE;
DROP TYPE IF EXISTS public.pr_status_tier CASCADE;

-- 1. STATE STATUS ENUM
-- Represents the SAP Purchase Requisition (PR) to Purchase Order (PO) lifecycle stages:
-- - STAGED: Requisition generated by store but pending manager sign-off.
-- - APPROVED: Verification completed, queued for batch dispatch.
-- - TRANSMITTED: Handshake completed, successfully routed to SAP S/4HANA.
CREATE TYPE public.pr_status_tier AS ENUM ('STAGED', 'APPROVED', 'TRANSMITTED');

-- 2. CREATE REQUISITION BATCHES REFERENCE TABLE
CREATE TABLE public.erp_requisition_batches (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    created_by UUID
);

COMMENT ON TABLE public.erp_requisition_batches IS 'Aggregated purchase order batches grouped and sent to SAP.';

-- 3. CREATE STAGED REQUISITIONS TABLE
-- Models SAP EBAN (Purchase Requisition) and EBKN (Account Assignment) table attributes.
CREATE TABLE public.erp_staged_requisitions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    
    -- SAP Material Number (MATNR). Target SKU for purchase.
    sku VARCHAR(40) NOT NULL,
    
    -- SAP Order Quantity (MENGE). Number of units to order.
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    
    -- SAP Plant Code (WERKS). Receiving warehouse plant.
    plant VARCHAR(4) NOT NULL,
    
    -- SAP Storage Location (LGORT). Receiving store storage location.
    storage_location VARCHAR(4) NOT NULL,
    
    -- PR Status Tier. Tracks verification workflow.
    status public.pr_status_tier DEFAULT 'STAGED'::public.pr_status_tier NOT NULL,
    
    -- Requisition Approver UID (USNAM equivalent). Reference to authorizing store manager.
    approved_by UUID,
    
    -- Requisition Approval Timestamp (ERDAT/UZEIT equivalent).
    approved_at TIMESTAMP WITH TIME ZONE,
    
    -- Consolidated Batch Linkage. FK referencing erp_requisition_batches.
    batch_id UUID REFERENCES public.erp_requisition_batches(id) ON DELETE SET NULL,
    
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

COMMENT ON TABLE public.erp_staged_requisitions IS 'Staged purchase requisitions matching SAP S/4HANA EBAN/EBKN structures.';

