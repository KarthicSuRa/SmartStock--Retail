-- 6. THE APPROVAL STORED PROCEDURE
-- Validates manager signature, transitions targets from STAGED to APPROVED,
-- and aggregates financial yield gains based on sales margin definitions.
CREATE OR REPLACE FUNCTION public.approve_staged_requisitions(
    target_skus TEXT[],
    manager_uid TEXT
)
RETURNS TABLE (
    total_approved_items INTEGER,
    total_approved_qty BIGINT,
    total_financial_yield NUMERIC(10, 2)
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_manager_uuid UUID;
BEGIN
    -- Force typecast check
    v_manager_uuid := manager_uid::UUID;

    -- Update matched staged records to APPROVED status
    UPDATE public.erp_staged_requisitions
    SET 
        status = 'APPROVED'::public.pr_status_tier,
        approved_by = v_manager_uuid,
        approved_at = timezone('utc'::text, now()),
        updated_at = timezone('utc'::text, now())
    WHERE sku = ANY(target_skus)
      AND status = 'STAGED'::public.pr_status_tier;

    -- Return consolidated summary of the approved items
    RETURN QUERY
    SELECT 
        COUNT(r.id)::INTEGER AS total_approved_items,
        COALESCE(SUM(r.quantity), 0)::BIGINT AS total_approved_qty,
        COALESCE(SUM(r.quantity * l.sales_margin), 0.00)::NUMERIC(10, 2) AS total_financial_yield
    FROM public.erp_staged_requisitions r
    LEFT JOIN public.live_inventory_ledger l 
      ON r.sku = l.sku 
     AND r.plant = l.sap_plant_code 
     AND r.storage_location = l.sap_storage_loc
    WHERE r.sku = ANY(target_skus)
      AND r.status = 'APPROVED'::public.pr_status_tier
      AND r.approved_by = v_manager_uuid
      AND r.approved_at >= timezone('utc'::text, now()) - INTERVAL '1 minute';
END;
$$;

COMMENT ON FUNCTION public.approve_staged_requisitions(text[], text) IS 'Approves staged requisitions and aggregates financial yield metrics.';

-- 7. THE SAP BATCH OPTIMIZER VIEW
-- Prepares multi-line OData $batch structures grouped by Vendor Account (LIFNR) for edge worker transmission.
CREATE OR REPLACE VIEW public.v_sap_consolidated_batch_payload AS
SELECT 
    pir.vendor_id,
    pir.vendor_name,
    COUNT(r.id)::INTEGER AS total_requisitions,
    SUM(r.quantity)::BIGINT AS total_quantity,
    json_agg(
        json_build_object(
            'sku', r.sku,
            'plant', r.plant,
            'storage_location', r.storage_location,
            'quantity', r.quantity,
            'netpr_price', pir.netpr_price,
            'matkl_group', pir.matkl_group
        )
    ) AS items
FROM public.erp_staged_requisitions r
JOIN public.erp_purchase_info_records pir ON r.sku = pir.sku
WHERE r.status = 'APPROVED'::public.pr_status_tier
GROUP BY pir.vendor_id, pir.vendor_name;

COMMENT ON VIEW public.v_sap_consolidated_batch_payload IS 'Vendor consolidated PO payloads formatted for SAP $batch OData structures.';
